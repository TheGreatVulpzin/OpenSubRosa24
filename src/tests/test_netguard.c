static int g_fail;

/* Test the proposed action index rule without changing the packet guard in the server. */
static int security_input(uint8_t *buf, int len, int *masked)
{
    int result = sv_netguard_input(buf, len, masked);
    if (result == SV_GUARD_PASS && len > 62 && memcmp(buf, "7DFP\x04", 5) == 0) {
        /* action_start spans bits 4..7 of byte 61 and bits 0..3 of byte 62. */
        if (buf[62] & 0x0c) {
            buf[62] &= 0xf3;
            (*masked)++;
        }
    }
    return result;
}

static void check(int cond, const char *what)
{
    printf("%s: %s\n", cond ? "ok  " : "FAIL", what);
    if (!cond)
        g_fail = 1;
}

/* A capture of the proxy (sv_packets.bin, tools/net/capture.py): every received datagram
 * goes through the guard. Real clients must give 0 masked and 0 dropped. */
static int run_capture(const char *path)
{
    static uint8_t buf[65536 + 16];
    unsigned char head[17];  /* direction, time, tick, ip, port, size (<BIIIHH) */
    unsigned inputs = 0, masked_total = 0, dropped = 0;
    FILE *f = fopen(path, "rb");
    if (!f || fread(buf, 1, 12, f) != 12 || memcmp(buf, "SVPK", 4) != 0) {
        printf("FAIL: %s is not a capture\n", path);
        return 1;
    }
    while (fread(head, 1, sizeof head, f) == sizeof head) {
        unsigned n = head[15] | head[16] << 8;
        int masked;
        if (fread(buf, 1, n, f) != n)
            break;
        if (head[0] != 0 || n < 5 || buf[4] != 4)
            continue;
        inputs++;
        if (security_input(buf, (int)n, &masked) == SV_GUARD_DROP)
            dropped++;
        masked_total += (unsigned)masked;
    }
    fclose(f);
    printf("%s: %u input packets, %u indexes masked, %u dropped\n", path, inputs, masked_total, dropped);
    return inputs == 0 || masked_total || dropped;
}

int main(int argc, char **argv)
{
    uint8_t buf[256];
    int masked, n;

    if (argc == 2 && strcmp(argv[1], "--sanitize") == 0) {
        unsigned char raw[65536];
        size_t size, i;
        _setmode(_fileno(stdin), _O_BINARY);
        size = fread(raw, 1, sizeof raw, stdin);
        if (security_input(raw, (int)size, &masked) == SV_GUARD_DROP)
            puts("DROP");
        else {
            for (i = 0; i < size; i++)
                printf("%02x", raw[i]);
            putchar('\n');
        }
        return 0;
    }
    if (argc > 1)
        return run_capture(argv[1]);

    memcpy(buf, good, sizeof good);
    check(sv_netguard_input(buf, sizeof good, &masked) == SV_GUARD_PASS && masked == 0, "good packet passes");
    check(memcmp(buf, good, sizeof good) == 0, "good packet unchanged");

    memcpy(buf, bad, sizeof bad);
    check(sv_netguard_input(buf, sizeof bad, &masked) == SV_GUARD_PASS && masked == 3, "bad packet: 3 indexes masked");
    check(sizeof bad == sizeof fixed && memcmp(buf, fixed, sizeof fixed) == 0, "bad packet equals the fixed packet");

    for (n = 5; n < (int)sizeof good - 2; n++) {
        memcpy(buf, good, sizeof good);
        if (sv_netguard_input(buf, n, &masked) != SV_GUARD_DROP) {
            printf("cut at %d bytes not dropped\n", n);
            g_fail = 1;
            break;
        }
    }
    check(n == (int)sizeof good - 2, "every copy of the good packet cut before its last voice byte is dropped");

    for (n = 0; n < 256; n++) {
        memcpy(buf, good, sizeof good);
        buf[61] = (uint8_t)((buf[61] & 15) | ((n & 15) << 4));
        buf[62] = (uint8_t)((buf[62] & 0xf0) | (n >> 4));
        if (!(security_input(buf, sizeof good, &masked) == SV_GUARD_PASS &&
              masked == (n >= 64) && (((buf[61] >> 4) | ((buf[62] & 15) << 4)) == (n & 63)) &&
              (buf[61] & 15) == (good[61] & 15) && (buf[62] & 0xf0) == (good[62] & 0xf0)))
            break;
    }
    check(n == 256, "all 256 action indexes stay below 64 and preserve adjacent fields");

    buf[0] = '7', buf[1] = 'D', buf[2] = 'F', buf[3] = 'P', buf[4] = 2;
    check(sv_netguard_input(buf, 5, &masked) == SV_GUARD_PASS, "other packet types pass");
    return g_fail;
}
