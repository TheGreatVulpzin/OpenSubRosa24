"""Make build/lift/client_win/cl_count_table.c for the call counter of the client proxy.

The counter hooks the same functions as the generated hook tables (hooks_lifted.c and
hooks_record.c): it takes the function start, the prologue length and the prologue bytes
from them. It also lists the GLee stubs, whose prologue the counter handles by itself.

Usage: python -I instrumentation/client/gen_count_table.py
"""
import csv
import re
import sys

LIFT = 'build/lift/client_win/'
OUT = LIFT + 'cl_count_table.c'


def names():
    out = {}
    with open('analysis/client_win/functions.csv', newline='') as f:
        for row in csv.DictReader(f):
            if row['name']:
                out[int(row['rva'], 16)] = row['name']
    return out


def read_table(path, known):
    text = open(path).read()
    arrays = {}
    for m in re.finditer(r'static uint8_t (expect_\w+)\[\d+\] = \{([^}]*)\};', text):
        arrays[m.group(1)] = [int(x, 16) for x in m.group(2).split(',')]
    relocs = {}
    for m in re.finditer(r'relocate\((expect_\w+), (\d+)\);', text):
        relocs.setdefault(m.group(1), []).append(int(m.group(2)))
    entries = []
    for m in re.finditer(r'\{ "(\w+)", (0x[0-9a-f]+), \(void \*\)\w+, (\d+), (expect_\w+), mask_all', text):
        rva = int(m.group(2), 16)
        name = known.get(rva) or m.group(1).replace('record_', '').replace('lf_', 'f')
        entries.append((rva, name, int(m.group(3)), arrays[m.group(4)], relocs.get(m.group(4), [])))
    return entries


def main():
    known = names()
    seen = set()
    hooks = []
    for table in ('hooks_lifted.c', 'hooks_record.c'):
        for e in read_table(LIFT + table, known):
            if e[0] not in seen:
                seen.add(e[0])
                hooks.append(e)
    stubs = []
    with open('analysis/client_win/glee_names.csv', newline='') as f:
        for row in csv.DictReader(f):
            if row['name'].startswith('GLee_Lazy_'):
                stubs.append((int(row['rva'], 16), row['name'][len('GLee_Lazy_'):]))

    o = ['/* Generated by instrumentation/client/gen_count_table.py. Do not edit. */',
         '#define WIN32_LEAN_AND_MEAN', '#include <windows.h>', '', '#include "hook.h"', '',
         '#define CL_COUNT_MAX 4096', 'volatile LONG cl_count[CL_COUNT_MAX];',
         'static void *cl_tramp[%d];' % len(hooks),
         'static const uint8_t mask_all[32] = { %s };' % ', '.join(['0xff'] * 32), '']
    for i, (rva, name, plen, expect, relocs) in enumerate(hooks):
        o.append('static uint8_t cx%d[%d] = { %s };' % (i, len(expect), ', '.join('0x%02x' % b for b in expect)))
    o.append('')
    for i in range(len(hooks)):
        o.append('__declspec(naked) static void ct%d(void) { __asm { pushfd\n lock inc dword ptr [cl_count + %d]\n'
                 ' popfd\n jmp dword ptr [cl_tramp + %d] } }' % (i, 4 * i, 4 * i))
    o.append('')
    o.append('SvHook cl_count_hooks[] = {')
    for i, (rva, name, plen, expect, relocs) in enumerate(hooks):
        o.append('    { "%s", 0x%x, (void *)ct%d, %d, cx%d, mask_all, &cl_tramp[%d], 1, 0 },' % (name, rva, i, plen, i, i))
    o.append('};')
    o.append('const int cl_count_nhooks = %d;' % len(hooks))
    o.append('')
    o.append('/* An absolute address in a prologue moves with ASLR: the counter adds the delta. */')
    o.append('const struct { int hook, offset; } cl_count_relocs[] = {')
    for i, (rva, name, plen, expect, relocs) in enumerate(hooks):
        for off in relocs:
            o.append('    { %d, %d },' % (i, off))
    o.append('    { -1, 0 } };')
    o.append('')
    o.append('const struct { uint32_t rva; const char *name; } cl_count_stubs[] = {')
    for rva, name in stubs:
        o.append('    { 0x%x, "%s" },' % (rva, name))
    o.append('};')
    o.append('const int cl_count_nstubs = %d;' % len(stubs))
    open(OUT, 'w', newline='\n').write('\n'.join(o) + '\n')
    print('hooks %d, stubs %d -> %s' % (len(hooks), len(stubs), OUT))


if __name__ == '__main__':
    sys.exit(main())
