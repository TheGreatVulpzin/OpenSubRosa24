"""Write build/client_image/client_gl.c: the OpenGL function pointer slots of the standalone client.

The game keeps one pointer slot for each OpenGL extension function it calls. The original start-up
fills the slots through GLee. The standalone client puts a small function in each slot. The
function looks up the real OpenGL function on its first call. The prototypes come from
analysis/client_win/gl_slots.csv, the same file that types the slots in Ghidra.

Usage: python -I instrumentation/client/gen_gl_slots.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CSV = ROOT / 'analysis/client_win/gl_slots.csv'
OUT = ROOT / 'build/client_image/client_gl.c'
TYPES_OUT = ROOT / 'src/lifted/lift_gl_client.h'

C_TYPES = {'uint': 'unsigned', 'int': 'int', 'float': 'float'}


def c_type(t):
    t = t.strip()
    stars = '*' * t.count('*')
    base = t.replace('*', '').strip()
    return C_TYPES.get(base, base) + (' ' + stars if stars else '')


def parse(proto):
    m = re.fullmatch(r'(.+?)\s*\*?(\w+)\((.*)\)', proto)
    ret = c_type(proto[:proto.index(m.group(2))])
    params = [] if m.group(3).strip() == 'void' else [p.strip() for p in m.group(3).split(',')]
    out = []
    for p in params:
        name = re.search(r'(\w+)$', p).group(1)
        out.append((c_type(p[:len(p) - len(name)]), name))
    return ret, m.group(2), out


def main():
    # The prototype keeps its commas, so the line splits into four fields only.
    rows = [dict(zip(('rva', 'name', 'cc', 'prototype'), line.rstrip('\n').split(',', 3)))
            for line in open(CSV, encoding='utf-8').readlines()[1:] if line.strip()]
    lines = [
        '/* Generated by instrumentation/client/gen_gl_slots.py. Do not edit. */',
        '#include <stdint.h>', '',
        'void *sr_import(const char *dll, const char *name);',
        'extern uintptr_t sr_base;', '',
        'static void *gl_proc(const char *name)',
        '{',
        '    static void *(__cdecl *lookup)(const char *);',
        '    if (!lookup)',
        '        lookup = (void *(__cdecl *)(const char *))sr_import("SDL2.dll", "SDL_GL_GetProcAddress");',
        '    return lookup(name);',
        '}', '',
    ]
    for r in rows:
        ret, name, params = parse(r['prototype'])
        plist = ', '.join(f'{t}{n}' if t.endswith('*') or t.endswith('* ') else f'{t} {n}' for t, n in params) or 'void'
        tlist = ', '.join(t for t, _ in params) or 'void'
        args = ', '.join(n for _, n in params)
        call = f'real({args})'
        lines += [
            f'static {ret} __stdcall gl_{name}({plist})',
            '{',
            f'    static {ret} (__stdcall *real)({tlist});',
            '    if (!real)',
            f'        real = ({ret} (__stdcall *)({tlist}))gl_proc("{name}");',
            f'    {"" if ret == "void" else "return "}{call};',
            '}', '',
        ]
    # The function types of the slots, for the lifted C (the Ghidra type of a slot is "glXxx *").
    types = ['/* Generated by instrumentation/client/gen_gl_slots.py. Do not edit. */',
             '#ifndef LIFT_GL_CLIENT_H', '#define LIFT_GL_CLIENT_H', '']
    for r in rows:
        ret, name, params = parse(r['prototype'])
        types.append(f'typedef {ret} (__stdcall {name})({", ".join(t for t, _ in params) or "void"});')
    types += ['', '#endif', '']
    TYPES_OUT.write_text('\n'.join(types), encoding='utf-8', newline='\n')
    lines += ['void client_gl_init(void)', '{']
    for r in rows:
        name = r['name']
        lines.append(f'    *(void **)(sr_base + {r["rva"]}u) = (void *)gl_{name};')
    lines += ['}', '']
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{OUT}: {len(rows)} slots')


if __name__ == '__main__':
    main()
