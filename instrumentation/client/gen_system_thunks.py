"""Make build/lift/client_win/system_thunks.c: the system library functions for the image targets.

The clean client code calls OpenGL, SDL2, OpenAL, Speex and winsock by name. The native client
links the real libraries. The image targets (the proxy wsock32.dll and the harness) have no such
import library: each call must go through the import of the target. A thunk has the name and the
calling convention of the system function and forwards to sr_import (the test environment in the
harness, the recorder in the live client). The winsock thunks use the os_* calls, which the test
environment and the recorder already know.

Usage: python -I instrumentation/client/gen_system_thunks.py
"""
import csv
import re

IMPORTS = 'analysis/client_win/imports.csv'
SLOTS = 'analysis/client_win/gl_slots.csv'
OUT = 'build/lift/client_win/system_thunks.c'

TYPE_WORDS = {'int', 'char', 'float', 'double', 'short', 'long', 'unsigned', 'void', 'signed'}

# Winsock of the clean client. Each thunk calls the os_* function of src/include/sr_os.h.
WINSOCK = [
    ('unsigned', 'socket', 'int af, int type, int protocol', 'return (unsigned)os_socket(af, type, protocol);'),
    ('int', 'ioctlsocket', 'unsigned s, long cmd, unsigned long *arg', 'return os_ioctlsocket(s, cmd, arg);'),
    ('int', 'bind', 'unsigned s, void *addr, int len', 'return os_bind(s, addr, len);'),
    ('uint32_t', 'inet_addr', 'const char *text', 'return os_inet_addr(text);'),
    ('void *', 'gethostbyname', 'const char *name', 'return os_gethostbyname(name);'),
]


def split_params(text):
    text = text.strip()
    if text in ('', 'void'):
        return []
    return [p.strip() for p in text.split(',')]


def parse_param(text, index):
    """Return (type, name) of one parameter. A parameter with no name gets a0, a1, ..."""
    match = re.match(r'^(.*?)(\w+)$', text)
    if not match or match.group(2) in TYPE_WORDS or not match.group(1).strip():
        return text, 'a%d' % index
    return match.group(1).strip(), match.group(2)


def thunk(row):
    match = re.match(r'^(.*?)(\w+)\((.*)\)$', row['prototype'])
    ret = match.group(1).strip()
    name = match.group(2)
    params = [parse_param(p, i) for i, p in enumerate(split_params(match.group(3)))]
    cc = row['cc']
    sig = ', '.join('%s %s' % (t if not t.endswith('*') else t + ' ', n) for t, n in params) or 'void'
    cast_types = ', '.join(t for t, _ in params) or 'void'
    args = ', '.join(n for _, n in params)
    cast = '%s (%s *)(%s)' % (ret, cc, cast_types)
    call = '((%s)p)(%s)' % (cast, args)
    body = '%s%s;' % ('' if ret == 'void' else 'return ', call)
    return ('%s %s %s(%s)\n{\n    static void *p;\n    if (!p) p = sr_import("%s", "%s");\n    %s\n}\n'
            % (ret, cc, name, sig, row['dll'], name, body))


def main():
    out = ['/* Generated by instrumentation/client/gen_system_thunks.py. Do not edit. */',
           '#include <stdint.h>',
           '#include "sr_os.h"',
           '',
           'void *sr_import(const char *dll, const char *name);',
           '']
    count = 0
    with open(IMPORTS, newline='') as handle:
        reader = csv.reader(handle)
        next(reader)
        for fields in reader:
            # The prototype holds commas and is not quoted: the rest of the line is the prototype.
            row = {'dll': fields[0], 'name': fields[1], 'cc': fields[2], 'prototype': ','.join(fields[3:])}
            if row['dll'].upper().startswith('STEAM'):
                continue
            out.append(thunk(row))
            count += 1
    for ret, name, params, body in WINSOCK:
        out.append('%s __stdcall %s(%s)\n{\n    %s\n}\n' % (ret, name, params, body))
        count += 1
    # GLee of the image targets. The real GLee needs an OpenGL context and the import library. Here
    # GLeeInit copies the extension pointers that the game stored in its own slots.
    out.append('extern uintptr_t sr_base;')
    out.append('')
    slots = []
    with open(SLOTS, newline='') as handle:
        next(handle)
        for line in handle:
            if line.strip():
                rva, name = line.strip().split(',', 2)[:2]
                slots.append((rva, name))
    for rva, name in slots:
        out.append('void *GLeeFuncPtr_%s;' % name)
    out.append('')
    out.append('unsigned char GLeeInit(void)\n{')
    for rva, name in slots:
        out.append('    GLeeFuncPtr_%s = *(void **)(sr_base + %su);' % (name, rva))
    out.append('    return 1;\n}\n')
    out.append('unsigned char GLeeEnabled(unsigned char *flag)\n{\n    (void)flag;\n    return 1;\n}\n')
    with open(OUT, 'w', newline='\n') as handle:
        handle.write('\n'.join(out))
    print('%d thunks -> %s' % (count, OUT))


main()
