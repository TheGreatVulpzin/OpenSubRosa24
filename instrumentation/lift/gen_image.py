"""Write instrumentation/standalone/image_024d.c for differential recordings.

- .rdata (strings, float constants, tables) and the initialized part of .data (0xe00 bytes).
  The rest of .data is zero memory.
- The relocations outside .text: words of .rdata and .data that hold an image address. The
  server adds its own delta to each one, as the Windows loader does.

The recording runtime copies these to their RVAs in its test image and sets sr_base.
The normal server uses independent definitions from tools/re/gen_storage.py.

Usage: python -I instrumentation/lift/gen_image.py
"""
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXE = ROOT / 'original/blackhouser/subrosadedicated024d.exe'
OUT = ROOT / 'instrumentation/standalone/image_024d.c'


def sections(d):
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    n = struct.unpack_from('<H', d, pe + 6)[0]
    opt = struct.unpack_from('<H', d, pe + 20)[0]
    size_of_image = struct.unpack_from('<I', d, pe + 24 + 56)[0]
    out = {}
    for i in range(n):
        o = pe + 24 + opt + 40 * i
        name = d[o:o + 8].rstrip(b'\0').decode()
        vsize, va, rsize, roff = struct.unpack_from('<IIII', d, o + 8)
        out[name] = (va, vsize, d[roff:roff + rsize])
    return out, size_of_image


def relocations(d, secs):
    va, size, raw = secs['.reloc']
    out, i = [], 0
    while i + 8 <= len(raw):
        page, blk = struct.unpack_from('<II', raw, i)
        if blk == 0:
            break
        for j in range(8, blk, 2):
            e = struct.unpack_from('<H', raw, i + j)[0]
            if e >> 12 == 3:  # IMAGE_REL_BASED_HIGHLOW
                out.append(page + (e & 0xfff))
        i += blk
    return out


def c_bytes(name, data):
    rows = [', '.join(f'0x{b:02x}' for b in data[k:k + 16]) for k in range(0, len(data), 16)]
    return f'const unsigned char {name}[{len(data)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def main():
    d = EXE.read_bytes()
    secs, size_of_image = sections(d)
    text_va, text_size, _ = secs['.text']
    rel = [r for r in relocations(d, secs) if not text_va <= r < text_va + text_size]
    rdata_va, _, rdata = secs['.rdata']
    data_va, _, data = secs['.data']
    lines = [
        '/* Generated by instrumentation/lift/gen_image.py from subrosadedicated024d.exe. Do not edit. */',
        '#include "image_024d.h"', '',
        f'const unsigned sr_image_size = 0x{size_of_image:x}u;',
        f'const unsigned sr_image_rdata_rva = 0x{rdata_va:x}u;',
        f'const unsigned sr_image_data_rva = 0x{data_va:x}u;', '',
        '/* RVAs of the words of .rdata and .data that hold an image address (base 0x400000). */',
        f'const unsigned sr_image_relocs[{len(rel)}] = {{ ' + ', '.join(f'0x{r:x}u' for r in rel) + ' };',
        f'const unsigned sr_image_reloc_count = {len(rel)};', '',
        c_bytes('sr_image_rdata', rdata),
        f'const unsigned sr_image_rdata_size = {len(rdata)};', '',
        c_bytes('sr_image_data', data),
        f'const unsigned sr_image_data_size = {len(data)};', '',
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{OUT}: .rdata {len(rdata)} bytes, .data {len(data)} bytes, {len(rel)} relocations, '
          f'image 0x{size_of_image:x}')


if __name__ == '__main__':
    main()
