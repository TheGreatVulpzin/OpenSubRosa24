"""Generate the storage adapter of the client from analysis/client_win/storage.csv.

The clean game code reads its data through sr_data_<name>. In the client build, each name is a
place in the image of subrosa.exe: sr_base plus the client RVA. This file is the client version of
instrumentation/runtime/storage_adapter.h. A name without a client address (not in the
csv, or dropped) gets a private dummy object, so the file still compiles. A function that uses a dummy
must not be adopted: tools/re/check_adopted.py finds those functions.

Usage: python -I tools/re/gen_client_storage.py
Output: instrumentation/client/runtime/storage_adapter.h
"""
import csv
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKIP = {'dropped'}


def main():
    lines = ['/* Generated by tools/re/gen_client_storage.py from analysis/client_win/storage.csv. Do not edit. */',
             '#ifndef SR_STORAGE_ADAPTER_H', '#define SR_STORAGE_ADAPTER_H',
             '#include "sr_storage_types.h"',
             'extern uintptr_t sr_base;',
             '#define SR_AT(type, rva) ((type *)(sr_base + (rva)))', '']
    names = set()
    unplaced = []
    rows = list(csv.DictReader((ROOT / 'analysis/client_win/storage.csv').open(encoding='utf-8')))
    rows.sort(key=lambda r: int(r['client_rva'], 16))
    for r in rows:
        if r['status'] in SKIP:
            continue
        typ, count, rva = r['type'], int(r['count']), int(r['client_rva'], 16)
        expr = f'(({typ} *)(sr_base + 0x{rva:x}u))'
        lines.append(f'#define sr_data_{r["name"]} ' + (expr if count > 1 else f'(*{expr})'))
        names.add(r['name'])
    # Objects without a client address: a private dummy of the same type.
    schema = runpy.run_path(str(ROOT / 'tools/re/gen_storage.py'))['schema']()
    dummies = []
    lines.append('')
    for _, name, typ, count, size in schema:
        if name in names:
            continue
        total = count * size
        arr = f'[{count}]' if count > 1 else ''
        lines.append(f'extern {typ} sr_unplaced_{name}{arr};')
        lines.append(f'#define sr_data_{name} sr_unplaced_{name}')
        if total <= (32 << 20):
            dummies.append(f'{typ} sr_unplaced_{name}{arr};')
        names.add(name)
        unplaced.append(name)
    # Globals that only the client has: analysis/client_win/group_globals_C<n>.csv, one file for each group.
    # Columns: name, type, count, client_rva, evidence. The clean client code uses cl_data_<name>.
    client_only = []
    for f in sorted((ROOT / 'analysis/client_win').glob('group_globals_C*.csv')):
        for r in csv.DictReader(f.open(encoding='utf-8')):
            count, rva = int(r['count'] or 1), int(r['client_rva'], 16)
            expr = f'(({r["type"]} *)(sr_base + 0x{rva:x}u))'
            client_only.append(f'#define cl_data_{r["name"]} ' + (expr if count > 1 else f'(*{expr})'))
    if client_only:
        lines.append('')
        lines.append('#include "sr_image_types.h"')
        lines.extend(client_only)
    # Fields that the server keeps in the packet workspace object.
    if 'packet_workspace' in names:
        lines.append('')
        for name in ('kickedip', 'objectpacket', 'itemtype', 'numofkicked'):
            lines.append(f'#define sr_data_{name} sr_data_packet_workspace.{name}')
    lines.extend(['', '#endif'])
    out = ROOT / 'instrumentation/client/runtime/storage_adapter.h'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    src = ['/* Generated by tools/re/gen_client_storage.py. Do not edit. */', '#include "sr_runtime.h"', '', *dummies]
    for fname, body in (('storage_unplaced.c', src), ('unplaced.txt', unplaced)):
        (out.parent / fname).write_text('\n'.join(body) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(names) - len(unplaced)} placed, {len(unplaced)} unplaced (dummies) in the client adapter')


if __name__ == '__main__':
    main()
