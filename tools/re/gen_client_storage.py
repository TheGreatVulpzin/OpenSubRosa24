"""Generate the storage adapter of the client from analysis/client_win/storage.csv.

The clean game code reads its data through sr_data_<name>. In the client build, each name is a
place in the image of subrosa.exe: sr_base plus the client RVA. This file is the client version of
instrumentation/runtime/storage_adapter.h. A name without a client address (not in the
csv, or dropped) gets a private dummy object, so the file still compiles. A function that uses a dummy
must not be adopted: tools/re/check_adopted.py finds those functions.

Usage: python -I tools/re/gen_client_storage.py
Output: instrumentation/client/runtime/storage_adapter.h
"""
import csv
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKIP = {'dropped'}
PACKET_FIELDS = ('kickedip', 'objectpacket', 'itemtype', 'numofkicked')


def main():
    lines = ['/* Generated by tools/re/gen_client_storage.py from analysis/client_win/storage.csv. Do not edit. */',
             '#ifndef SR_STORAGE_ADAPTER_H', '#define SR_STORAGE_ADAPTER_H',
             '#include "sr_storage_types.h"',
             '#define sr_voice_channel_type VoiceChannelClient',
             'extern uintptr_t sr_base;',
             '#define SR_AT(type, rva) ((type *)(sr_base + (rva)))', '']
    names = set()
    unplaced = []
    rows = list(csv.DictReader((ROOT / 'analysis/client_win/storage.csv').open(encoding='utf-8')))
    rows.sort(key=lambda r: int(r['client_rva'], 16))
    for r in rows:
        if r['status'] in SKIP:
            continue
        typ, count, rva = r['type'], int(r['count']), int(r['client_rva'], 16)
        expr = f'(({typ} *)(sr_base + 0x{rva:x}u))'
        lines.append(f'#define sr_data_{r["name"]} ' + (expr if count > 1 else f'(*{expr})'))
        names.add(r['name'])
    # Objects without a client address: a private dummy of the same type.
    schema = runpy.run_path(str(ROOT / 'tools/re/gen_storage.py'))['schema']()
    dummies = []
    lines.append('')
    for _, name, typ, count, size in schema:
        if name in names:
            continue
        total = count * size
        arr = f'[{count}]' if count > 1 else ''
        lines.append(f'extern {typ} sr_unplaced_{name}{arr};')
        lines.append(f'#define sr_data_{name} sr_unplaced_{name}')
        if total <= (32 << 20):
            dummies.append(f'{typ} sr_unplaced_{name}{arr};')
        names.add(name)
        unplaced.append(name)
    # Per-system addresses include client data and shared packet fields.
    # Packet fields use an explicit client address when the address table supplies one.
    client_only = []
    shared_fields = set()
    for f in sorted((ROOT / 'analysis/client_win').glob('group_globals_C*.csv')):
        for r in csv.DictReader(f.open(encoding='utf-8')):
            count, rva = int(r['count'] or 1), int(r['client_rva'], 16)
            expr = f'(({r["type"]} *)(sr_base + 0x{rva:x}u))'
            prefix = 'cl_data_'
            if r['name'] in PACKET_FIELDS:
                prefix = 'sr_data_'
                shared_fields.add(r['name'])
                client_only.append(f'#undef {prefix}{r["name"]}')
            client_only.append(f'#define {prefix}{r["name"]} ' + (expr if count > 1 else f'(*{expr})'))
            if r['name'] == 'game_tick':
                # The client keeps the tick before the place of Game.ticks. The shared code
                # reads it as Game.ticks, a signed int.
                client_only.append(f'#define sr_game_ticks (*((int *)(sr_base + 0x{rva:x}u)))')
            if r['name'] == 'game_tick':
                client_only.append('void __cdecl debug_addcross(const vec3 *center, float size);')
                client_only.append('#define sr_debug_cross(center, size) debug_addcross((center), (size))')
                client_only.append('void __cdecl debug_addatafloat(const char *name, float value);')
                client_only.append('#define sr_debug_float(name, value) debug_addatafloat((name), (value))')
                client_only.append('void __cdecl debug_addline(const vec3 *from, const vec3 *to);')
                client_only.append('#define sr_debug_line(from, to) debug_addline((from), (to))')
                client_only.append('void area_reset_interiors(void);')
                client_only.append('#define sr_area_reset_interiors() area_reset_interiors()')
                client_only.append('int __cdecl lf_e9d70(int texture, int type);')
                client_only.append('#define sr_window_atlas(texture, type) lf_e9d70((texture), (type))')
                client_only.append('#define sr_object_frame_orthogonal 0')
                client_only.append('void level_client_landscape(void);')
                client_only.append('#define sr_level_after_landscape() level_client_landscape()')
                client_only.append('void level_client_finish(void);')
                client_only.append('#define sr_level_after_buildings() level_client_finish()')
                client_only.append('#define sr_level_shop_count 4')
                client_only.append('#define sr_human_floor_all_rays 1')
                client_only.append('#define sr_timer_name(field, name) ((void)0)')
                client_only.append('#define sr_timer_start(field) ((void)0)')
                client_only.append('#define sr_timer_stop(field) ((void)0)')
                client_only.append('extern int sr_client_gametype;')
                client_only.append('#define sr_option_gametype(o) (*((void)(o), &sr_client_gametype))')
                client_only.append('extern int sr_client_end_time;')
                client_only.append('#define sr_game_end_time sr_client_end_time')
            if r['name'] == 'open_file':
                # The client keeps the handle of the open file in one global. The text parser
                # stores its handle there, not in a field of Parser.
                client_only.append(f'#define sr_parser_file (*((void **)(sr_base + 0x{rva:x}u)))')
    if client_only:
        lines.append('')
        lines.append('#include "sr_image_types.h"')
        lines.append('#include "sr_audio_types.h"')
        lines.append('#include "sr_input_types.h"')
        lines.extend(client_only)
    # Fields that the server keeps in the packet workspace object.
    if 'packet_workspace' in names:
        lines.append('')
        for name in PACKET_FIELDS:
            if name not in shared_fields:
                lines.append(f'#define sr_data_{name} sr_data_packet_workspace.{name}')
    lines.extend(['', '#endif'])
    out = ROOT / 'instrumentation/client/runtime/storage_adapter.h'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    dummies.append('int sr_client_end_time;')
    dummies.append('int sr_client_gametype;')
    src = ['/* Generated by tools/re/gen_client_storage.py. Do not edit. */', '#include "sr_runtime.h"', '', *dummies]
    for fname, body in (('storage_unplaced.c', src), ('unplaced.txt', unplaced)):
        (out.parent / fname).write_text('\n'.join(body) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(names) - len(unplaced)} placed, {len(unplaced)} unplaced (dummies) in the client adapter')


if __name__ == '__main__':
    main()
