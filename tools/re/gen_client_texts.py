"""Write src/client/image/texts.c: the error and assert texts of the image decoders.

The decoders name a text by its place in the .rdata of the client (an enum constant in
src/client/image/*.c). The tool finds each constant of the kinds *_ERROR_*, *_ASSERT_* and
*_SOURCE*, reads the text from the client executable and writes it as a C string. A text that
image_check passes is a wide string, the other texts are narrow.

Usage: python -I tools/re/gen_client_texts.py          write src/client/image/texts.c
       python -I tools/re/gen_client_texts.py --check  compare texts.c with the executable
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXE = ROOT / "original/client/subrosa.exe"
OUT = ROOT / "src/client/image/texts.c"
KIND = re.compile(r"\b(\w+_(?:ERROR|ASSERT|SOURCE)\w*)\s*=\s*(0x[0-9a-f]+)")
WIDE_CALL = re.compile(r",\s*(\w+)\s*,\s*(\w+)\s*,\s*(?:0x[0-9a-f]+|\d+)\s*\)\s*;")


def sections(data):
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    count = struct.unpack_from("<H", data, pe + 6)[0]
    optional = struct.unpack_from("<H", data, pe + 20)[0]
    out = []
    for i in range(count):
        o = pe + 24 + optional + 40 * i
        vsize, va, rsize, roff = struct.unpack_from("<IIII", data, o + 8)
        out.append((va, max(vsize, rsize), data[roff:roff + rsize]))
    return out


def read_text(secs, rva, wide):
    for va, size, raw in secs:
        if va <= rva < va + size:
            chunk = raw[rva - va:]
            if wide:
                end = 0
                while end + 1 < len(chunk) and chunk[end:end + 2] != b"\0\0":
                    end += 2
                return chunk[:end].decode("utf-16-le")
            return chunk[:chunk.index(b"\0")].decode("latin-1")
    raise SystemExit(f"rva {rva:#x} is in no section")


def collect():
    narrow, wide = {}, {}
    names = {}
    sources = sorted((ROOT / "src/client/image").glob("*.c"))
    sources = [s for s in sources if s.name != "texts.c"]
    for path in sources:
        text = path.read_text(encoding="utf-8")
        for name, rva in KIND.findall(text):
            names[name] = int(rva, 16)
        for m in WIDE_CALL.finditer(text):
            for arg in m.groups():
                if arg in names:
                    wide[arg] = names[arg]
    for name, rva in names.items():
        if name not in wide:
            narrow[name] = rva
    return narrow, wide


def c_string(value, wide):
    out = []
    for ch in value:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= code < 127:
            out.append(ch)
        else:
            out.append(f"\\x{code:02x}\"\"")
    return ("L" if wide else "") + '"' + "".join(out) + '"'


def build():
    secs = sections(EXE.read_bytes())
    narrow, wide = collect()
    rows = {"narrow": {}, "wide": {}}
    for name, rva in narrow.items():
        rows["narrow"][rva] = read_text(secs, rva, False)
    for name, rva in wide.items():
        rows["wide"][rva] = read_text(secs, rva, True)
    return rows


def render(rows):
    lines = ["/* Generated by tools/re/gen_client_texts.py. Do not edit. */",
             "#include \"image/texts.h\"", "",
             "/* Texts of the image decoders, sorted by place. */",
             "static const struct { unsigned rva; const char *text; } narrow_texts[] = {"]
    for rva in sorted(rows["narrow"]):
        lines.append(f"    {{ {rva:#x}, {c_string(rows['narrow'][rva], False)} }},")
    lines += ["};", "", "static const struct { unsigned rva; const wchar_t *text; } wide_texts[] = {"]
    for rva in sorted(rows["wide"]):
        lines.append(f"    {{ {rva:#x}, {c_string(rows['wide'][rva], True)} }},")
    lines += ["};", "",
              "/* The text at a place of the executable. A place with no text gives an empty text. */",
              "const char *cl_text(unsigned rva)",
              "{",
              "    unsigned i;",
              "    for (i = 0; i < sizeof narrow_texts / sizeof narrow_texts[0]; i++)",
              "        if (narrow_texts[i].rva == rva)",
              "            return narrow_texts[i].text;",
              "    return \"\";",
              "}", "",
              "/* The wide text at a place of the executable. */",
              "const wchar_t *cl_wtext(unsigned rva)",
              "{",
              "    unsigned i;",
              "    for (i = 0; i < sizeof wide_texts / sizeof wide_texts[0]; i++)",
              "        if (wide_texts[i].rva == rva)",
              "            return wide_texts[i].text;",
              "    return L\"\";",
              "}", ""]
    return "\n".join(lines)


def main():
    rows = build()
    text = render(rows)
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        # The first line is the comment of the plain source file.
        if current.split("\n", 1)[1:] != text.split("\n", 1)[1:]:
            print("texts.c does not match the executable")
            sys.exit(1)
        print(f"texts.c matches: {len(rows['narrow'])} narrow, {len(rows['wide'])} wide")
        return
    if "--write-src" not in sys.argv[1:]:
        print("texts.c is a plain source file. Use --check to compare it with the executable, or --write-src to replace it.")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT}:{len(rows['narrow'])} narrow, {len(rows['wide'])} wide")


if __name__ == "__main__":
    main()
