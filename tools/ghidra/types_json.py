"""Write build/ghidra/types.json for tools/ghidra/ApplyTypes.java.

Inputs:
  src/include/sr_types.h        the structs (generated by tools/re/gen_types.py, pack(1))
  analysis/024d/globals.csv     global names and RVAs
  analysis/024d/manual_globals.csv
  analysis/024d/data_globals.csv  globals with a base type (int, float, char*...) and a count.
                                  A name here wins over the same name in the files above.

The struct fields are read from sr_types.h, which has one field per line. Offsets follow
from pack(1), and the script checks them against the "+0x..." comments and the sizes.

Usage: python -I tools/ghidra/types_json.py
"""
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/re'))
import gen_types  # noqa: E402

BASE_SIZE = {'int': 4, 'uint32_t': 4, 'float': 4, 'char': 1, 'uint8_t': 1, 'int16_t': 2}

# "typedef struct vec3 {...} vec3;" or "typedef union Human { struct {...}; uint8_t lf_raw[N]; } Human;"
STRUCT_RE = re.compile(r'typedef (?:struct (\w+) \{(.*?)\}|union (\w+) \{ struct \{(.*?)\}; uint8_t lf_raw\[[^\]]+\]; \}) (\w+);', re.S)
FIELD_RE = re.compile(r'^\s*(\w+)\s+([\w,\s]+?)(?:\[([^\]]+)\])?\s*;')


def array_count(text):
    # "0x25d64 - 0x3c": numbers joined by + and -.
    total, sign = 0, 1
    for tok in re.findall(r'0x[0-9a-fA-F]+|\d+|[+-]', text):
        if tok in '+-':
            sign = 1 if tok == '+' else -1
        else:
            total += sign * int(tok, 0)
    return total


def parse_structs(text):
    """name -> {'size', 'fields': [{'name', 'offset', 'type', 'count'}]}, in file order."""
    structs = {}
    for m in STRUCT_RE.finditer(text):
        name, body = m.group(5), m.group(2) if m.group(2) is not None else m.group(4)
        fields, pos = [], 0
        decls = []
        for line in body.splitlines():
            c = re.search(r'/\*\s*\+0x([0-9a-fA-F]+)', line)
            code = re.sub(r'/\*.*?\*/', '', line)
            # "typedef struct vec3 { float x, y, z; } vec3;": a line can hold several fields.
            for part in code.split(';'):
                if part.strip():
                    decls.append((part + ';', c.group(1) if c else None))
        for decl, off in decls:
            f = FIELD_RE.match(decl)
            if not f:
                continue
            typ, names, count = f.group(1), f.group(2), f.group(3)
            count = array_count(count) if count else 0
            for fname in (n.strip() for n in names.split(',')):
                size = BASE_SIZE[typ] if typ in BASE_SIZE else structs[typ]['size']
                if off is not None and int(off, 16) != pos:
                    raise SystemExit(f'ERROR: {name}.{fname}: comment says +0x{off}, pack(1) gives 0x{pos:x}')
                # Byte arrays are unknown bytes (pad_, unk_): Ghidra keeps them without a field.
                if typ != 'uint8_t':
                    fields.append({'name': fname, 'offset': pos, 'type': typ, 'count': count})
                pos += size * max(count, 1)
        structs[name] = {'size': pos, 'fields': fields}
    return structs


def main():
    structs = parse_structs((ROOT / 'src/include/sr_types.h').read_text(encoding='utf-8'))
    for cname, (_glob, size) in gen_types.STRUCTS.items():
        if structs[cname]['size'] != size:
            raise SystemExit(f'ERROR: {cname} has 0x{structs[cname]["size"]:x} bytes, expected 0x{size:x}')
    rows = {}
    for path in ('analysis/024d/globals.csv', 'analysis/024d/manual_globals.csv'):
        with open(ROOT / path, encoding='utf-8') as fh:
            for r in csv.DictReader(fh):
                rows[r['name']] = int(r['rva'], 16)
    by_glob = {g: c for c, (g, _s) in gen_types.STRUCTS.items()}
    by_glob.update({'game': 'Game', 'account': 'Account'})
    globals_ = []
    for name, rva in sorted(rows.items(), key=lambda x: x[1]):
        typ = by_glob.get(name)
        count = gen_types.COUNTS.get(name, 0) if typ != 'Game' else 0
        if name == 'account':
            # The records start after the key and the counter (sr_global_table.h).
            globals_.append({'name': 'account_header', 'rva': rva, 'type': None, 'count': 0})
            rva += 8
        globals_.append({'name': name, 'rva': rva, 'type': typ, 'count': count})
    with open(ROOT / 'analysis/024d/data_globals.csv', encoding='utf-8') as fh:
        typed = {r['name']: r for r in csv.DictReader(fh)}
    globals_ = [g for g in globals_ if g['name'] not in typed]
    for name, r in typed.items():
        globals_.append({'name': name, 'rva': int(r['rva'], 16), 'type': r['type'],
                         'count': int(r['count']) if r['count'] else 0})
    globals_.sort(key=lambda g: g['rva'])
    # getpaths copies the fread and fwrite addresses into these globals (main_loop.c).
    globals_ += [{'name': 'p_fread', 'rva': 0x91022a4, 'type': '*fread', 'count': 0},
                 {'name': 'p_fwrite', 'rva': 0x13bf2d00, 'type': '*fwrite', 'count': 0}]
    # The lifter turns each global into a #define. A g_ prefix keeps the macros away from
    # the field names (Game.ticks, Game.timer) and the local names.
    for g in globals_:
        g['name'] = 'g_' + g['name']
    out = ROOT / 'build/ghidra'
    out.mkdir(parents=True, exist_ok=True)
    data = {'structs': [{'name': n, **s} for n, s in structs.items()], 'globals': globals_}
    (out / 'types.json').write_text(json.dumps(data, indent=1), encoding='utf-8')
    print(f'types.json: {len(structs)} structs, {len(globals_)} globals')


if __name__ == '__main__':
    main()
